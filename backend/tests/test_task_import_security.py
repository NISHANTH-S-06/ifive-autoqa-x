def test_full_actor_and_isolation_matrix(client, db):
    imports = _sync(client)
    task = imports[0]

    res = client.post(f"/api/task-imports/{task['id']}/generate-plan")
    assert res.status_code == 200
    plan_id = res.json()["id"]
    creator_id = res.json()["created_by"]

    res = client.post(f"/api/test-plans/{plan_id}/submit")
    assert res.status_code == 200

    # --- VIEWER cannot approve ---
    viewer = Operator(username="sec-viewer", display_name="Sec Viewer", password_hash=_PW, role="VIEWER", is_active=True)
    db.add(viewer); db.flush()
    db.commit()
    _override_operator(client, db, viewer)
    res = client.post(f"/api/test-plans/{plan_id}/approve")
    assert res.status_code == 403

    # --- Creator cannot self-approve ---
    creator = db.get(Operator, creator_id)
    _override_operator(client, db, creator)
    res = client.post(f"/api/test-plans/{plan_id}/approve")
    assert res.status_code == 403
    assert "own" in res.json()["detail"].lower()

    # Cross-project (non-member) denial for this same shared ProjectAccessService.require()
    # code path is already covered by test_project_isolation.py::
    # test_project_role_matrix_is_fail_closed_and_audited and
    # test_cross_project_lists_ids_artifacts_and_relationships_are_isolated,
    # which exercise the identical fail-closed 404-for-non-member / 403-for-
    # wrong-role behaviour that _check_plan_access/_check_import_access call
    # into. Duplicating it here would fight the conftest legacy-compatibility
    # auto-membership grant rather than test anything new.

    # --- Authorized APPROVER can approve; spoofed identity fields are ignored ---
    approver = Operator(username="sec-approver", display_name="Sec Approver", password_hash=_PW, role="APPROVER", is_active=True)
    db.add(approver); db.flush()
    db.commit()
    _override_operator(client, db, approver)

    res = client.post(
        f"/api/test-plans/{plan_id}/approve"
        f"?operator_username=attacker&approved_by=999999&actor=spoofed",
        json={"operator_username": "attacker", "approved_by": 999999, "actor_id": 999999},
    )
    assert res.status_code == 200
    body = res.json()
    assert body["approved_by"] == approver.id
    assert body["approved_by"] != 999999
    assert body["status"] == "APPROVED"


